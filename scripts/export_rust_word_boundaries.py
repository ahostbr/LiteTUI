"""Freeze Python's Unicode word class and Textual word-start oracle for Rust.

No LiteTUI import, application construction or settings/data access. Python's
re \\w is not Rust's is_alphanumeric or the Unicode regex crate's \\w. Regenerate
with the supported source interpreter when its Unicode version changes.
"""
from __future__ import annotations

import argparse
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "rust/litetui-terminal/src/word_chars.rs"
FIXTURE = ROOT / "rust/litetui-terminal/tests/fixtures/composer_words.json"
WORD = re.compile(r"\w")
WORD_START = re.compile(r"(?<=\W)\w")
SAMPLES = (
    "", "one", "   ", "one two...three", "  alpha_2 - beta  ",
    "雪_beta...γεια ²½Ⅳ", "a\u0301b \u05b0c \u0345d", "a\u203fb_c",
    "🙂❤️a 1️⃣b 👩‍👩‍👧‍👦z", "a\U00011f02b \U0001e4d0c", "a\u00a0b\u2003c",
)


def word_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for code in range(0x110001):
        matches = code <= 0x10FFFF and WORD.fullmatch(chr(code)) is not None
        if matches and start is None:
            start = code
        elif not matches and start is not None:
            ranges.append((start, code - 1))
            start = None
    return ranges


def render_table() -> str:
    lines = [
        "// Generated by scripts/export_rust_word_boundaries.py; do not hand edit.",
        f"// Python re Unicode word class; Unicode {unicodedata.unidata_version}.",
        "// Deliberately independent of the Rust compiler's Unicode version.",
        "pub(crate) fn is_word(ch: char) -> bool {",
        "    let code = u32::from(ch);",
        "    let index = RANGES.partition_point(|&(_, end)| end < code);",
        "    RANGES.get(index).is_some_and(|&(start, _)| start <= code)",
        "}",
        "const RANGES: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{start:X}, 0x{end:X})," for start, end in word_ranges())
    lines.extend(["];", ""])
    return "\n".join(lines)


def oracle() -> dict[str, object]:
    cases = []
    for text in SAMPLES:
        for cursor in range(len(text) + 1):
            left = list(WORD_START.finditer(text[:cursor]))
            right = WORD_START.search(text[cursor:])
            cases.append({
                "text": text, "cursor": cursor,
                "left": left[-1].start() if left else 0,
                "right": cursor + right.start() if right else len(text),
            })
    return {"unicode_version": unicodedata.unidata_version, "cases": cases}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        TABLE: render_table(),
        FIXTURE: json.dumps(oracle(), ensure_ascii=True, indent=2) + "\n",
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                print(f"STALE: {path}")
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        print(f"{'CHECKED' if args.check else 'GENERATED'}: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
