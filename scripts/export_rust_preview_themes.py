"""Export public dark theme fixtures for the offline Rust preview, never live settings.

Only the audited themes module and Textual color math are imported, not LiteTUI/App.
The eventual live catalog must come from Python, including custom themes and saves.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from textual.color import Color
from textual.theme import BUILTIN_THEMES, Theme

from litetui import themes

OUTPUT = ROOT / "rust/litetui-terminal/src/theme_catalog.rs"


def resolved_colors(theme: Theme) -> dict[str, tuple[int, int, int]]:
    variables = theme.to_color_system().generate()
    extras = themes.extra_defaults(primary=variables["primary"], bone=variables["foreground"])
    extras.update(theme.variables)
    values = {
        "background": variables["background"],
        "surface": variables["surface"],
        "panel": variables["panel"],
        "tool_background": variables["surface-darken-2"],
        "foreground": variables["foreground"],
        "title": variables["success"],
        "assistant_border": variables["success-darken-2"],
        "thinking_text": extras["thinking-text"],
        "thinking_border": extras["thinking-box"],
        "tool_text": extras["tool-text"],
        "error": variables["error"],
        "footer_foreground": extras.get("footer-foreground", variables["foreground"]),
        "footer_background": extras.get("footer-background", variables["background"]),
    }
    return {name: Color.parse(value).rgb for name, value in values.items()}


def public_catalog() -> dict[str, Theme]:
    return {name: theme for name, theme in sorted({**BUILTIN_THEMES, **themes.ALL_THEMES}.items())
            if theme.dark and name not in themes.LIGHT_BUILTINS}


def render_catalog() -> str:
    source_hash = hashlib.sha256(Path(themes.__file__).read_bytes()).hexdigest()
    lines = [
        "// Generated by scripts/export_rust_preview_themes.py; do not hand edit.",
        f"// themes.py SHA256: {source_hash}; Textual {importlib.metadata.version('textual')}",
        "// Public fixtures only: no saved settings or user custom themes read.",
        "pub fn builtin_themes() -> Vec<Theme> {", "    vec![",
    ]
    for name, theme in public_catalog().items():
        lines.extend(["        Theme {", f"            name: {json.dumps(name)}.into(),"])
        for field, (red, green, blue) in resolved_colors(theme).items():
            lines.append(f"            {field}: Color::Rgb({red}, {green}, {blue}),")
        lines.append("        },")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_catalog()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("STALE: regenerate the public Rust theme fixture")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"{len(public_catalog())} public dark themes; no live settings read")


if __name__ == "__main__":
    main()
