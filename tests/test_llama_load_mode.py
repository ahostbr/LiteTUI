"""T1306-F (P9): b12078 replaced --mmap / --mlock with ONE --load-mode MODE.

b12078 (19e8a86fe) common/arg.cpp:2642-2658 accepts auto | none | mmap | mlock | mmap+mlock | dio,
default auto (common/common.h:493). Its --help lists no --mmap or --mlock at all, so a model with
either Load-tab key set used to be refused (IniUnexpressible) and could not load on that build.

The two booleans become one value. A key the user left unset takes b9360's default
(common/common.h:548 `use_mmap = true`, :550 `use_mlock = false`), so the model loads as it did.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from litetui import llm_backend
from litetui.llm_backend import IniUnexpressible, ModelRow, render_preset_ini
from litetui.settings import Settings

FIXTURES = Path(__file__).parent / "fixtures"


def _census(build: str) -> frozenset[str]:
    return llm_backend.parse_supported_flags((FIXTURES / f"llama_server_help_{build}.txt").read_text(encoding="utf-8"))


@pytest.fixture(autouse=True)
def _pinned(monkeypatch):
    monkeypatch.setattr(llm_backend, "sibling_mmproj", lambda path: (None, ()))
    monkeypatch.setattr(llm_backend, "configured_build", lambda settings: "cuda:b9360")


def _render(monkeypatch, flags, profiles: dict, keys="abcd") -> str:
    monkeypatch.setattr(llm_backend, "installed_flags", lambda *a: flags)
    s = Settings()
    s.llama_load_settings = profiles
    return render_preset_ini([ModelRow(k, f"C:/m/{k}.gguf", "custom") for k in keys], s)


def _section(body: str, key: str) -> list[str]:
    block = body.split(f"[{key}]\n", 1)[1].split("\n\n", 1)[0]
    return block.splitlines()


def test_the_fixtures_are_what_this_card_assumes():
    b9360, b12078 = _census("b9360"), _census("b12078")
    assert {"mmap", "mlock"} <= b9360 and "load-mode" not in b9360
    assert "load-mode" in b12078 and not {"mmap", "mlock"} & b12078


@pytest.mark.parametrize("mmap,mlock,mode", [
    (True, True, "mmap+mlock"),
    (True, False, "mmap"),
    (False, True, "mlock"),
    (False, False, "none"),
    (True, None, "mmap"),          # mlock unset: b9360 default off
    (False, None, "none"),
    (None, True, "mmap+mlock"),    # mmap unset: b9360 default on
    (None, False, "mmap"),
])
def test_b12078_gets_one_load_mode_line(monkeypatch, mmap, mlock, mode):
    cfg = {k: v for k, v in (("mmap", mmap), ("mlock", mlock)) if v is not None}
    lines = _section(_render(monkeypatch, _census("b12078"), {"a": {**cfg, "ctx": 8192}}, keys="a"), "a")
    assert f"load-mode = {mode}" in lines
    assert not [ln for ln in lines if ln.startswith(("mmap ", "mlock "))]
    assert "ctx-size = 8192" in lines


def test_b12078_with_neither_key_writes_no_load_mode(monkeypatch):
    body = _render(monkeypatch, _census("b12078"), {"a": {"ctx": 8192}}, keys="a")
    assert "load-mode" not in body


def test_control_b9360_ini_is_byte_identical(monkeypatch):
    """Golden captured from b822fd74 (before this card) with the same profiles and census."""
    body = _render(monkeypatch, _census("b9360"), {
        "a": {"mmap": False, "mlock": True, "ctx": 8192},
        "b": {"mmap": True},
        "c": {"mlock": False, "ngl": 99},
    })
    assert body == (
        "; generated by LiteTUI llm_backend — edit /modelcfg, not this file\n; engine: cuda:b9360\n\n"
        "[*]\ncache-idle-slots = false\ncache-ram = 32768\nslot-prompt-similarity = 0.5\n\n"
        "[a]\nmodel = C:/m/a.gguf\nctx-size = 8192\nmlock = true\nmmap = false\n\n"
        "[b]\nmodel = C:/m/b.gguf\nmmap = true\n\n"
        "[c]\nmodel = C:/m/c.gguf\nmlock = false\nn-gpu-layers = 99\n\n"
        "[d]\nmodel = C:/m/d.gguf\n"
    )


def test_control_a_build_with_neither_form_still_refuses(monkeypatch):
    flags = _census("b12078") - {"load-mode"}
    with pytest.raises(IniUnexpressible):
        _render(monkeypatch, flags, {"a": {"mlock": True}}, keys="a")


@pytest.mark.parametrize("build", ["b9360", "b12078"])
def test_mmap_and_mlock_are_expressible_on_both_builds(build):
    """The Model screen's "n/a in installed build" reads this, not the raw flag name."""
    flags = _census(build)
    assert llm_backend.load_key_expressible("mmap", flags)
    assert llm_backend.load_key_expressible("mlock", flags)


def test_control_expressible_still_says_no_when_nothing_carries_it():
    flags = _census("b12078") - {"load-mode"}
    assert not llm_backend.load_key_expressible("mmap", flags)
    assert not llm_backend.load_key_expressible("mlock", flags)
    assert llm_backend.load_key_expressible("ctx", flags)
    assert llm_backend.load_key_expressible("mmap", frozenset())   # unknown census: not claimed n/a


@pytest.mark.parametrize("build", ["b9360", "b12078"])
def test_the_router_argv_flags_exist_on_both_builds(build):
    """The flags `_spawn` passes the router (llm_backend.py, `_spawn`)."""
    flags = _census(build)
    for flag in ("models-preset", "host", "port", "models-max", "no-models-autoload"):
        assert flag in flags, f"--{flag} missing from {build}"


def test_the_model_screen_uses_the_expressible_check():
    src = (Path(llm_backend.__file__).parent / "plugins" / "model_switch.py").read_text(encoding="utf-8")
    assert "load_key_expressible(" in src
